// Type de variable : les chaînes de caractères: String, les entier: int, les nombre a virgule: double, les booléens: bool 
/* 
NB: les variables sont sensibles à la casse (majuscules et minuscules) et doivent commencer par une lettre ou un underscore (_)
  et ne peuvent pas contenir d'espaces ni de caractères spéciaux (sauf l'underscore).
  et ne peuvent pas être des mots réservés (comme if, else, for, etc.)
  et le type String commence par une majuscule, les autres types commencent par une minuscule.
*/
String city = "beni";
int age = 23;
double height = 2.7;
bool isTrue = true;

// A noter avec var, on peut déclarer une variable sans préciser son type, mais le type sera inféré par le compilateur en fonction de la valeur assignée à la variable.
var temperature = 25.5; // le type sera inféré comme double
var numberOfStudents = 30; // le type sera inféré comme int

